import { describe, expect, it, vi } from 'vitest'
import {
  parseCheckoutSession,
  type GivingPaymentState,
  type GivingTarget,
} from '../src/models'
import {
  FlutterwaveGivingPayment,
  PayPalGivingPayment,
  trustedGivingCallback,
} from '../src/payment/hosted'
import type { GivingCheckoutContext } from '../src/payment/types'

function checkout(provider: string, target: GivingTarget): GivingCheckoutContext {
  return {
    apiOrigin: 'https://api.thefaithapp.com',
    target,
    session: parseCheckoutSession({
      provider,
      donation_id: 44,
      approval_url: 'https://checkout.example.com/approve',
    }),
    getAuthoritativeStatus: vi.fn(),
    waitForAuthoritativeStatus: vi.fn(async () => ({
      donationId: 44,
      provider,
      state: 'succeeded' as const,
    })),
    capturePayPal: vi.fn(async () => {}),
    verifyFlutterwave: vi.fn(async () => {}),
  }
}

interface HostedProps {
  successPaths: ReadonlySet<string>
  onApproved: (callback: URL) => Promise<GivingPaymentState>
}

describe('PayPal provider callbacks', () => {
  // These are the return URLs generated by the general/campaign API and
  // PayPalPartnerSubscriptions, rather than invented SDK-only callback paths.
  it.each([
    [{ type: 'general' }, '/paypal/giving/success'],
    [{ type: 'general' }, '/paypal/giving/billing-approved'],
    [{ type: 'campaign', campaignId: 12 }, '/paypal/campaigns/success'],
  ] as const)('captures approved checkout %j at %s', async (target, path) => {
    const context = checkout('paypal', target)
    const payment = PayPalGivingPayment({
      checkout: context,
      onComplete: vi.fn(),
      onError: vi.fn(),
    })
    const hosted = payment.props as HostedProps
    const callback = trustedGivingCallback(
      `${context.apiOrigin}${path}?donation_id=44`,
      context.apiOrigin,
      44,
      hosted.successPaths,
    )

    expect(callback).not.toBeNull()
    expect(await hosted.onApproved(callback!)).toBe('succeeded')
    expect(context.capturePayPal).toHaveBeenCalledOnce()
    expect(context.waitForAuthoritativeStatus).toHaveBeenCalledOnce()
  })
})

describe('Flutterwave provider callbacks', () => {
  function payment(target: GivingTarget = { type: 'general' }) {
    const context = checkout('flutterwave', target)
    const element = FlutterwaveGivingPayment({
      checkout: context,
      onComplete: vi.fn(),
      onError: vi.fn(),
    })
    return { context, hosted: element.props as HostedProps }
  }

  it.each([
    [{ type: 'general' }, '/flutterwave/giving/callback'],
    [{ type: 'campaign', campaignId: 12 }, '/flutterwave/campaigns/callback'],
  ] as const)('verifies the provider transaction for %j', async (target, path) => {
    const { context, hosted } = payment(target)
    const callback = trustedGivingCallback(
      `${context.apiOrigin}${path}?donation_id=44&status=successful&transaction_id=987`,
      context.apiOrigin,
      44,
      hosted.successPaths,
    )

    expect(callback).not.toBeNull()
    expect(await hosted.onApproved(callback!)).toBe('succeeded')
    expect(context.verifyFlutterwave).toHaveBeenCalledWith('987')
    expect(context.waitForAuthoritativeStatus).toHaveBeenCalledOnce()
  })

  it.each(['cancelled', 'failed'])(
    'preserves %s without verifying a payment',
    async (status) => {
      const { context, hosted } = payment()
      expect(
        await hosted.onApproved(
          new URL(
            `https://api.thefaithapp.com/flutterwave/giving/callback?status=${status}`,
          ),
        ),
      ).toBe(status)
      expect(context.verifyFlutterwave).not.toHaveBeenCalled()
      expect(context.waitForAuthoritativeStatus).not.toHaveBeenCalled()
    },
  )

  it('rejects approval without a provider transaction identifier', async () => {
    const { context, hosted } = payment()
    await expect(
      hosted.onApproved(
        new URL(
          'https://api.thefaithapp.com/flutterwave/giving/callback?status=successful',
        ),
      ),
    ).rejects.toMatchObject({ code: 'payment_failed' })
    expect(context.verifyFlutterwave).not.toHaveBeenCalled()
  })
})
